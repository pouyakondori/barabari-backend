def add_persian_translations():
    # Load parsed JSON files
    with open('germany_constitution.json') as f:
        de_data = json.load(f)
    with open('portugal_constitution.json') as f:
        pt_data = json.load(f)
    
    # Germany: Translate article titles
    for chapter in de_data:
        for article in chapter['articles']:
            art_num = str(article['number'])
            if art_num in GERMANY_ARTICLE_TITLES_FA:
                article['title']['fa'] = GERMANY_ARTICLE_TITLES_FA[art_num]
            else:
                # Fallback: keep empty
                article['title']['fa'] = article['title'].get('fa', '')
    
    # Portugal: Translate article titles
    for chapter in pt_data:
        for article in chapter['articles']:
            art_num = article['number']
            if art_num in PORTUGAL_ARTICLE_TITLES_FA:
                article['title']['fa'] = PORTUGAL_ARTICLE_TITLES_FA[art_num]
            else:
                article['title']['fa'] = article['title'].get('fa', '')
    
    # Save updated JSON
    with open('germany_constitution.json', 'w') as f:
        json.dump(de_data, f, indent=2, ensure_ascii=False)
    with open('portugal_constitution.json', 'w') as f:
        json.dump(pt_data, f, indent=2, ensure_ascii=False)
    
    # Print stats
    de_translated = sum(1 for ch in de_data for art in ch['articles'] if art['title']['fa'])
    de_total = sum(1 for ch in de_data for art in ch['articles'])
    pt_translated = sum(1 for ch in pt_data for art in ch['articles'] if art['title']['fa'])
    pt_total = sum(1 for ch in pt_data for art in ch['articles'])
    
    print(f"Germany: {de_translated}/{de_total} article titles translated")
    print(f"Portugal: {pt_translated}/{pt_total} article titles translated")

if __name__ == '__main__':
    add_persian_translations()
